"""Pydantic schemas and data validation models for EventCraft AI.

Defines request structures, GenAI structured output definitions,
and OpenAPI response models for API endpoints.
"""

from __future__ import annotations
from typing import List, Optional, Literal
from pydantic import BaseModel, Field, field_validator


class PlanGenerationRequest(BaseModel):
    """Input payload required to synthesize a full intelligent event blueprint."""

    title: str = Field(..., min_length=3, max_length=150, description="Name or title of the celebration")
    eventType: Literal["WEDDING", "BIRTHDAY", "COMMUNITY"] = Field(..., description="Target event archetype")
    date: str = Field(..., pattern=r"^\d{4}-\d{2}-\d{2}$", description="Event target date in ISO YYYY-MM-DD")
    location: str = Field(..., min_length=2, max_length=150, description="City, region, or physical venue location")
    totalBudget: float = Field(..., gt=0, le=100_000_000, description="Overall expenditure cap")
    currency: str = Field(default="USD", max_length=10, description="ISO currency code (e.g. USD, EUR, INR)")
    guestCount: int = Field(..., ge=1, le=100_000, description="Expected attendee count")
    vibeTheme: str = Field(..., min_length=3, max_length=300, description="Atmospheric vision or thematic styling")
    specialRequests: Optional[str] = Field(default=None, max_length=1000, description="Specific constraints or user preferences")

    @field_validator("title", "location", "vibeTheme", mode="before")
    @classmethod
    def strip_whitespace(cls, v: str) -> str:
        if isinstance(v, str):
            return v.strip()
        return v


class BudgetItemGen(BaseModel):
    """Individual line item emitted during AI budget synthesis."""

    category: str = Field(..., max_length=100)
    name: str = Field(..., max_length=150)
    percentage: float = Field(..., ge=0.0, le=100.0, description="Percentage of total event budget allocated")
    priority: Literal["CRITICAL", "HIGH", "MEDIUM", "OPTIONAL"]
    notes: str = Field(..., max_length=500)


class MilestoneGen(BaseModel):
    """Production milestone item on the chronological schedule."""

    title: str = Field(..., max_length=150)
    phase: Literal["PLANNING", "FINAL_PREP", "DAY_OF", "POST_EVENT"]
    daysOffset: int = Field(..., description="Days relative to event date: negative for prep, 0 for day of, positive for follow-up")
    targetTime: Optional[str] = Field(default=None, max_length=20)
    description: str = Field(..., max_length=1000)


class VendorGen(BaseModel):
    """Vendor role specification, procurement guideline, and interview checklist."""

    category: str = Field(..., max_length=100)
    recommendedVendorRole: str = Field(..., max_length=150)
    estimatedPercentBudget: float = Field(..., ge=0.0, le=100.0)
    inquiryTemplate: str = Field(..., max_length=2000)
    keyQuestionsToAsk: List[str] = Field(default_factory=list)


class IdeaGen(BaseModel):
    """Creative concept or thematic recommendation."""

    type: Literal["THEME_CONCEPT", "PALETTE", "ACTIVITY", "COPYWRITING"]
    title: str = Field(..., max_length=150)
    content: str = Field(..., max_length=2000)
    tags: List[str] = Field(default_factory=list)


class GenAIFullPlan(BaseModel):
    """Exhaustive structured output model generated by Google Gemini AI."""

    eventSummary: str = Field(..., max_length=1000)
    budgetBreakdown: List[BudgetItemGen]
    milestones: List[MilestoneGen]
    vendors: List[VendorGen]
    personalizedIdeas: List[IdeaGen]
    contingencyAdvice: str = Field(..., max_length=1000)


# ============================================================================
# API Response Schemas
# ============================================================================

class BudgetItemResponse(BaseModel):
    id: str
    category: str
    name: str
    allocated: float
    spent: float
    priority: str
    notes: Optional[str] = None


class MilestoneResponse(BaseModel):
    id: str
    title: str
    phase: str
    daysOffset: int
    targetTime: Optional[str] = None
    description: Optional[str] = None
    status: str


class VendorResponse(BaseModel):
    id: str
    category: str
    name: str
    estimatedCost: float
    inquiryTemplate: str
    questions: List[str]


class IdeaResponse(BaseModel):
    id: str
    type: str
    title: str
    content: str
    tags: Optional[str] = None


class EventDetailModel(BaseModel):
    id: str
    title: str
    eventType: str
    date: str
    location: str
    totalBudget: float
    currency: str
    guestCount: int
    vibeTheme: str
    summary: Optional[str] = None
    contingencyAdvice: Optional[str] = None
    budgetItems: List[BudgetItemResponse]
    milestones: List[MilestoneResponse]
    vendors: List[VendorResponse]
    ideas: List[IdeaResponse]


class EventDetailResponse(BaseModel):
    event: EventDetailModel


class EventSummaryItem(BaseModel):
    id: str
    title: str
    eventType: str
    date: str
    location: str
    totalBudget: float
    currency: str
    guestCount: int
    summary: Optional[str] = None
    vibeTheme: str
    createdAt: Optional[str] = None
    budgetCount: int
    milestoneCount: int
    vendorCount: int


class EventListResponse(BaseModel):
    events: List[EventSummaryItem]
    total: int


class VendorListItem(BaseModel):
    id: str
    category: str
    roleName: str
    estimatedCost: float
    inquiryTemplate: str
    questions: List[str]
    eventTitle: Optional[str] = None
    eventDate: Optional[str] = None


class VendorListResponse(BaseModel):
    vendors: List[VendorListItem]


class GeneratePlanResponse(BaseModel):
    success: bool
    eventId: str
    cached: bool = False
